/**
 * Fast intelligent search that ranks matches:
 * 1. Exact or prefix code match (e.g. "CSE 22", "MATH")
 * 2. Prefix title match (e.g. "Data Struct")
 * 3. Substring match in title or major
 */
export function searchBscseCourses(query, limit = 8) {
  if (!query || typeof query !== "string") return [];
  const cleanQ = query.trim().toLowerCase().replace(/\s+/g, " ");
  if (cleanQ.length < 1) return [];

  const qNormalized = cleanQ.replace(/[^a-z0-9]/g, "");

  const scored = [];

  for (const c of BSCSE_COURSES) {
    const codeLower = c.code.toLowerCase();
    const titleLower = c.title.toLowerCase();
    const codeNorm = codeLower.replace(/[^a-z0-9]/g, "");

    let score = -1;

    if (codeLower === cleanQ || codeNorm === qNormalized) {
      score = 100;
    } else if (codeLower.startsWith(cleanQ) || codeNorm.startsWith(qNormalized)) {
      score = 80;
    } else if (titleLower.startsWith(cleanQ)) {
      score = 70;
    } else if (codeLower.includes(cleanQ) || codeNorm.includes(qNormalized)) {
      score = 60;
    } else if (titleLower.includes(cleanQ)) {
      score = 50;
    } else {
      // Word match in title
      const words = cleanQ.split(" ");
      const allWordsMatch = words.every((w) => titleLower.includes(w) || codeLower.includes(w));
      if (allWordsMatch) {
        score = 40;
      }
    }

    if (score > 0) {
      scored.push({ course: c, score });
    }
  }

  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, limit).map((item) => item.course);
}
